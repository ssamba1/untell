"""Recall on modern LLM essays, against topic-matched human essays.

Scores the essays from ``untell.bench.generate_ai`` twice — as generated, and with Markdown
scaffolding (headings, bold, bullets) stripped, which is what a submitted essay looks like — with
untell's calibrated verdict and each audited open detector, and reports recall at the default and
the recommended threshold, plus AUROC against the held-out PERSUADE human essays (same prompts).

    python -m untell.bench.modern_recall modern-ai.jsonl \\
        --cards docs/observatory/open-detectors --out docs/observatory/modern-llm.json

Human scores for AUROC come from the PERSUADE rows of each detector's report card. Per-essay
scores are written alongside the summary so every number can be re-derived.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from untell.evidence.corpus import load_corpus
from untell.evidence.scorers import resolve_scorer
from untell.evidence.stats import auroc, wilson_interval

_MD = [(re.compile(r"^\s{0,3}#{1,6}\s*.*$", re.M), ""),          # headings dropped
       (re.compile(r"\*\*(.+?)\*\*|__(.+?)__"), r"\1\2"),          # bold
       (re.compile(r"^\s*[-*+]\s+", re.M), ""),                     # bullet markers
       (re.compile(r"\n{3,}"), "\n\n")]


def strip_markdown(text: str) -> str:
    for pat, rep in _MD:
        text = pat.sub(rep, text)
    return text.strip()


def _rate(k: int, n: int) -> dict:
    lo, hi = wilson_interval(k, n) if n else (None, None)
    return {"k": k, "n": n, "rate": k / n if n else None, "ci95": [lo, hi]}


def _pct(r: dict) -> str:
    if r["rate"] is None:
        return "–"
    lo, hi = r["ci95"]
    return f"{100 * r['rate']:.0f}% ({r['k']}/{r['n']}; 95% CI {100 * lo:.0f}–{100 * hi:.0f}%)"


def render_markdown(out: dict) -> str:
    """The observatory page, generated from the JSON so the two cannot disagree."""
    prov = out.get("provenance", {})
    lines = ["# Recall on modern LLM essays", "",
             "*Generated by `python -m untell.bench.modern_recall` from "
             "[modern-llm.json](modern-llm.json); do not edit by hand.*", "",
             f"{out['n']} essays written by `{prov.get('model', '?')}` (sampled, temperature "
             f"{prov.get('temperature', '?')}, seeds recorded per essay) answering the same "
             f"{prov.get('prompts', '?')} PERSUADE 2.0 assignments the held-out human essays answer, "
             "prompted as a US student in grades 6–12. Each essay is scored as generated and with "
             "Markdown scaffolding (headings, bold, bullets) stripped, the way a pasted submission "
             "looks.", "",
             "| detector | threshold | recall, as generated | recall, Markdown stripped | "
             "AUROC vs PERSUADE human (stripped) |", "|---|---|---|---|---:|"]
    u = out["detectors"].get("untell (calibrated-v2)")
    if u:
        lines.append(f"| untell full tier (calibrated-v2) | 5% fit FPR | {_pct(u['recall']['as generated'])} "
                     f"| {_pct(u['recall']['markdown stripped'])} | – |")
    for model, e in out["detectors"].items():
        if model.startswith("untell"):
            continue
        a = e["auroc_vs_persuade_human"].get("markdown stripped")
        for label, key, th in (("0.5 (default)", "recall_default", None),
                               (f"{e['threshold']:.4f} (fitted)", "recall_recommended", e["threshold"])):
            lines.append(f"| {model} | {label} | {_pct(e[key]['as generated'])} | "
                         f"{_pct(e[key]['markdown stripped'])} | "
                         f"{'' if th else (f'{a:.3f}' if a is not None else '–')} |")
    lines += ["", "Recall is the share of these AI essays flagged. Compare with each detector's "
              "false-positive rates on human writing in the [open-detector leaderboard]"
              "(open-detectors.md) and [calibration](calibration.md): a recall figure means "
              "nothing without the false-flag rate paid for it.", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m untell.bench.modern_recall", description=__doc__.split("\n\n")[0])
    ap.add_argument("essays")
    ap.add_argument("--cards", required=True, help="open-detector cards folder (with thresholds.json)")
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    docs = load_corpus(args.essays, label="ai")
    cards = Path(args.cards)
    thresholds = json.loads((cards / "thresholds.json").read_text(encoding="utf-8"))["models"]
    variants = {"as generated": [d["text"] for d in docs],
                "markdown stripped": [strip_markdown(d["text"]) for d in docs]}
    first = docs[0].get("provenance") or {} if docs else {}
    out: dict = {"n": len(docs),
                 "provenance": {"model": first.get("model"), "temperature": first.get("temperature"),
                                "top_p": first.get("top_p"),
                                "prompts": len({(d.get("meta") or {}).get("prompt_name") for d in docs})},
                 "detectors": {}}

    from untell.scripts.score import score_text

    per_doc = [{"id": d["id"], "prompt_name": (d.get("meta") or {}).get("prompt_name"),
                "words": len(d["text"].split()), "scores": {}} for d in docs]
    res = {}
    for name, texts in variants.items():
        results = [score_text(t, tier="full") for t in texts]
        for row, r in zip(per_doc, results):
            row["scores"].setdefault("untell (calibrated-v2)", {})[name] = {
                "flagged": bool(r["flagged"]), "verdict_score": r.get("verdict_score")}
        flags = [r["flagged"] for r in results]
        res[name] = _rate(sum(flags), len(flags))
    out["detectors"]["untell (calibrated-v2)"] = {"recall": res}
    print("untell", {k: round(v["rate"], 3) for k, v in res.items()}, flush=True)

    for model, th in thresholds.items():
        card = json.loads((cards / (model.replace("/", "__") + ".json")).read_text(encoding="utf-8"))
        human = [r["score"] for r in card["documents"]
                 if r["label"] == "human" and r["group"] in ("ell", "non-ell") and r["score"] is not None]
        sc = resolve_scorer(f"hf:{model}", 0.5)
        entry = {"threshold": th["threshold"], "recall_default": {}, "recall_recommended": {},
                 "auroc_vs_persuade_human": {}}
        for name, texts in variants.items():
            scores = [sc.verdict(t).score for t in texts]
            for row, x in zip(per_doc, scores):
                row["scores"].setdefault(model, {})[name] = x
            entry["recall_default"][name] = _rate(sum(s >= 0.5 for s in scores), len(scores))
            entry["recall_recommended"][name] = _rate(sum(s >= th["threshold"] for s in scores), len(scores))
            entry["auroc_vs_persuade_human"][name] = auroc(scores, human)
        out["detectors"][model] = entry
        print(model, {k: round(v["rate"], 3) for k, v in entry["recall_default"].items()}, flush=True)
    out["documents"] = per_doc
    Path(args.out).write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    Path(args.out).with_suffix(".md").write_text(render_markdown(out), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
