BEGIN = "/* untell:variants:begin */"
END = "/* untell:variants:end */"


@pytest.fixture(scope="module")
def html() -> str:
    assert PAGE.is_file(), f"missing {PAGE}"
    return PAGE.read_text(encoding="utf-8")


def test_no_external_scripts_or_network_calls(html: str) -> None:
    assert not re.search(r"<script[^>]*\bsrc\s*=", html, re.I), "page must not load any script file"
    assert not re.search(r"<link[^>]*rel=[\"']?stylesheet", html, re.I), "no external stylesheets"
    for pattern in (
        r"\bfetch\s*\(",
        r"XMLHttpRequest",
        r"sendBeacon",
        r"\bWebSocket\b",
        r"EventSource",
    ):
        assert not re.search(pattern, html), f"network API in page: {pattern}"
    assert "connect-src 'none'" in html, "CSP should forbid network connections"


def test_section_ids_present(html: str) -> None:
    for element_id in SECTION_IDS:
        assert re.search(rf'id="{re.escape(element_id)}"', html), f"missing id={element_id}"


def test_preset_sources_cited(html: str) -> None:
    for url in SOURCE_URLS:
        assert url in html, f"missing source {url}"


def test_print_and_dark_mode_styles(html: str) -> None:
    assert "@media print" in html
    assert re.search(r"prefers-color-scheme:\s*dark", html)


def test_brief_footer_and_privacy_statement(html: str) -> None:
    assert (
        "Generated by untell (open source). Not legal advice. This page measures the detector, not the writer."
        in html
    )
    assert "never leaves your device" in html


def _variants_block(html: str) -> str:
    start, end = html.index(BEGIN), html.index(END)
    block = html[start:end]
    for dom in ("document.", "window.", "navigator."):
        assert dom not in block, f"variants block must be pure, found {dom}"
    return block


SAMPLE = (
    "She said \"it's fine\" -- but it wasn't... The results don't lie.  We tested red, green and blue.\r\n"
    "A second line in the same paragraph — with a dash. Then​ more.   \n"
    "\n"
    "\u201cYes,\u201d I'm sure that's the color they're analyzing. It is clear we are done. The 'quoted' word and the '90s.\n"
)


@pytest.mark.skipif(shutil.which("node") is None, reason="node not installed")
def test_null_variants_keep_the_same_words(html: str, tmp_path: Path) -> None:
    script = tmp_path / "run.js"
    script.write_text(
        _variants_block(html)
        + "\nconst input = "
        + json.dumps(SAMPLE)
        + ";\nconst g = UntellVariants.generateVariants(input);\n"
        + "console.log(JSON.stringify({g, curly: UntellVariants.toCurly('\"Hi,\" she said. It\\'s \\'x\\'.'),"
        + " words: UntellVariants.wordsOf('It’s  A—b.')}));\n",
        encoding="utf-8",
    )
    out = subprocess.run(
        ["node", str(script)], capture_output=True, text=True, timeout=30, check=True
    )
    data = json.loads(out.stdout)
    variants = {v["id"]: v for v in data["g"]["variants"]}

    assert data["g"]["dropped"] == [], (
        f"null variants failed the same-words check: {data['g']['dropped']}"
    )
    null_ids = [f"N{i}" for i in range(1, 11)]
    assert all(i in variants for i in null_ids)
    for vid in null_ids:
        assert variants[vid]["sameWords"], vid
    # This sample has something for every null edit to change.
    assert [vid for vid in null_ids if variants[vid]["noop"]] == []
    assert {"L1", "L2", "L3", "L4"} <= set(variants)

    assert data["curly"] == "“Hi,” she said. It’s ‘x’."
    assert "“" in variants["N1"]["text"] and "’" in variants["N1"]["text"]
    assert '"' not in variants["N1"]["text"]
    assert data["words"] == ["it", "s", "a", "b"]

    assert "it is fine" in variants["L1"]["text"] and "I am sure" in variants["L1"]["text"]
    assert "red, green, and blue" in variants["L3"]["text"]
    assert "colour" in variants["L4"]["text"] and "analysing" in variants["L4"]["text"]
    assert max(len(line) for line in variants["N6"]["text"].split("\n")) <= 72
